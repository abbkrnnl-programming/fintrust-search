# ---------------------------------------------------------------------------

def _init_pt() -> None:
    """Initialize PyTerrier."""
    import pyterrier as pt
    if not pt.java.started():
        pt.java.init()


def load_gold_qrels(path: Path = TEST_GOLD_PATH) -> pd.DataFrame:
    """
    Load gold qrels from CSV.

    Expected CSV columns: qid, docno, label (0 or 1).

    Args:
        path: Path to the annotated CSV file.

    Returns:
        Gold qrels DataFrame with columns [qid, docno, label].

    Raises:
        FileNotFoundError: If the annotation file has not been created yet.
    """
    if not path.exists():
        raise FileNotFoundError(
            f"Gold qrels not found at '{path}'.\n"
            "Run src/04_ground_truth.py first to generate test_gold.csv"
        )
    qrels = pd.read_csv(path)
    qrels["qid"] = qrels["qid"].astype(str)
    qrels["label"] = pd.to_numeric(qrels["label"], errors="coerce").fillna(0).astype(int)
    log.info("Gold qrels loaded — %d pairs  positive=%d",
             len(qrels), qrels["label"].sum())
    return qrels


