"""
06_evaluate.py — Final Evaluation.

Implements two evaluation stages:

    run_pt_experiment():
        Loads the gold qrels (generated by 04_ground_truth.py) and runs pt.Experiment
        comparing five retrieval pipelines:
            P0: BM25
            P1: BM25 + RM3
            P2: BM25 + Social features
            P3: BM25 + Graph features
            P4: BM25 + All features (Full LTR)
        Saves results to results/experiment_results.csv.

    run_ablation_study():
        Compares each feature group independently to quantify their
        individual contribution. Exports results/ablation_results.csv.

Inputs:
    data/processed/queries/test_queries.pkl
    data/processed/qrels/test_gold.csv
    data/processed/all_features.pkl
    models/ltr_model.pkl
    models/ltr_scaler.pkl
    index/

Outputs:
    results/experiment_results.csv
    results/ablation_results.csv

Usage:
    python src/06_evaluate.py experiment
    python src/06_evaluate.py ablation
"""

