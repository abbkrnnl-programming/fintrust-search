def run_ablation_study() -> pd.DataFrame:
    """
    Ablation study: measure the marginal contribution of each feature group.

    Compares five configurations:
        1. BM25 only (no features)
        2. BM25 + Social features
        3. BM25 + Graph features
        4. BM25 + Content features
        5. BM25 + All features (full model)

    Results are saved to results/ablation_results.csv.

    Returns:
        Ablation results DataFrame.
    """
    _init_pt()
    import pyterrier as pt
    import importlib
    indexer_mod = importlib.import_module("src.02_indexer")
    load_index = indexer_mod.load_index
    get_bm25_retriever = indexer_mod.get_bm25_retriever

    test_queries = load_pkl(TEST_QUERIES_PATH)
    gold_qrels   = load_gold_qrels()
    doc_features = load_pkl(ALL_FEATURES_PATH)
    model        = load_pkl(MODEL_PATH)
    scaler       = load_pkl(SCALER_PATH)

    index = load_index(INDEX_DIR)
    bm25  = get_bm25_retriever(index, num_results=1000)

    pipelines = [
        bm25,
        bm25 >> _build_feature_reranker(doc_features, SOCIAL_COLS,   model, scaler),
        bm25 >> _build_feature_reranker(doc_features, GRAPH_COLS,    model, scaler),
        bm25 >> _build_feature_reranker(doc_features, CONTENT_COLS,  model, scaler),
        bm25 >> _build_feature_reranker(doc_features, ALL_FEAT_COLS, model, scaler),
    ]
    names = [
        "BM25 only",
        "BM25 + Social",
        "BM25 + Graph",
        "BM25 + Content",
        "BM25 + Full LTR",
    ]

    log.info("Running ablation study (%d configurations)...", len(pipelines))
    ablation = pt.Experiment(
        pipelines,
        test_queries,
        gold_qrels,
        eval_metrics=["ndcg_cut_10", "map", "P_5"],
        names=names,
        baseline=0,
        verbose=True,
    )

    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    ablation.to_csv(ABLATION_RESULTS, index=False)
    log.info("Ablation results saved → %s", ABLATION_RESULTS)
    log.info("\n%s", ablation.to_string())
    return ablation


