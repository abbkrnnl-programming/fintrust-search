# Run pt.Experiment on test set
# ===========================================================================

def _build_feature_reranker(
    doc_features: pd.DataFrame,
    feature_cols: list[str],
    model,
    scaler,
    alpha: float = 0.3,
) -> object:
    """
    Build a PyTerrier Transformer that re-ranks using a subset of features.

    Args:
        doc_features: Full feature matrix indexed by docno.
        feature_cols: Subset of feature columns to use.
        model:        Trained LogisticRegression.
        scaler:       Fitted StandardScaler (fitted on all features).
        alpha:        BM25 weight in blended score.

    Returns:
        pt.apply.generic Transformer compatible with pt.Experiment.
    """
    import pyterrier as pt
    from src.utils import min_max_normalize  # type: ignore

    # Determine which scaler columns correspond to our feature_cols
    # The scaler was fitted on ["bm25_norm"] + ALL_FEAT_COLS
    all_cols_in_scaler = ["bm25_norm"] + ALL_FEAT_COLS
    col_indices = [0] + [all_cols_in_scaler.index(c) for c in feature_cols]

    def _rerank_fn(results: pd.DataFrame) -> pd.DataFrame:
        results = results.copy()
        # Normalize BM25 per query
        results["bm25_norm"] = (
            results.groupby("qid")["score"]
            .transform(lambda s: min_max_normalize(s))
            .fillna(0.0)
        )
        # Attach selected features
        feat_df = doc_features[feature_cols].reindex(results["docno"].values).fillna(0.0)
        X_full = pd.concat(
            [results[["bm25_norm"]].reset_index(drop=True),
             feat_df.reset_index(drop=True)],
            axis=1,
        ).values.astype(float)

        # Scale using only the relevant column indices
        X_scaled = scaler.transform(
            pd.DataFrame(
                [[0.0] * len(all_cols_in_scaler)] * len(X_full),
                columns=all_cols_in_scaler,
            ).assign(**{
                "bm25_norm": X_full[:, 0],
                **{c: X_full[:, i + 1] for i, c in enumerate(feature_cols)},
            }).values
        )

        p_rel = model.predict_proba(X_scaled)[:, 1]
        results["score"] = alpha * results["bm25_norm"] + (1 - alpha) * p_rel
        return results.sort_values(["qid", "score"], ascending=[True, False])

    return pt.apply.generic(_rerank_fn)


def run_pt_experiment() -> pd.DataFrame:
    """
    Run pt.Experiment comparing five retrieval pipelines on the gold test set.

    Pipelines evaluated:
        P0: BM25                — lexical baseline
        P1: BM25 + RM3          — query expansion baseline
        P2: BM25 + Social       — social trust features only
        P3: BM25 + Graph        — author authority features only
        P4: BM25 + Full LTR     — all four dimensions

    Metrics: nDCG@10, MAP@1000, P@5, RR@10.

    Returns:
        pt.Experiment results DataFrame.
    """
    _init_pt()
    import pyterrier as pt
    import importlib
    indexer_mod = importlib.import_module("src.02_indexer")
    load_index = indexer_mod.load_index
    get_bm25_retriever = indexer_mod.get_bm25_retriever

    test_queries  = load_pkl(TEST_QUERIES_PATH)
    gold_qrels    = load_gold_qrels()
    doc_features  = load_pkl(ALL_FEATURES_PATH)
    model         = load_pkl(MODEL_PATH)
    scaler        = load_pkl(SCALER_PATH)

    index = load_index(INDEX_DIR)
    bm25  = get_bm25_retriever(index, num_results=1000)

    # P0: BM25 baseline
    P0 = bm25

    # P1: BM25 + RM3 query expansion
    P1 = bm25 >> pt.rewrite.RM3(index, fb_terms=10, fb_docs=3) >> bm25

    # P2: BM25 + Social features only
    P2 = bm25 >> _build_feature_reranker(doc_features, SOCIAL_COLS,  model, scaler)

    # P3: BM25 + Graph features only
    P3 = bm25 >> _build_feature_reranker(doc_features, GRAPH_COLS,   model, scaler)

    # P4: BM25 + Full LTR (all features)
    P4 = bm25 >> _build_feature_reranker(doc_features, ALL_FEAT_COLS, model, scaler)

    pipelines = [P0, P1, P2, P3, P4]
    names     = ["BM25", "BM25+RM3", "BM25+Social", "BM25+Graph", "BM25+Full"]

    log.info("Running pt.Experiment with %d pipelines...", len(pipelines))
    experiment = pt.Experiment(
        pipelines,
        test_queries,
        gold_qrels,
        eval_metrics=["ndcg_cut_10", "map", "P_5", "recip_rank"],
        names=names,
        baseline=0,
        correction="b",        # Bonferroni correction for multiple comparisons
        verbose=True,
    )

    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    experiment.to_csv(EXPERIMENT_RESULTS, index=False)
    log.info("Experiment results saved → %s", EXPERIMENT_RESULTS)
    log.info("\n%s", experiment.to_string())
    return experiment


