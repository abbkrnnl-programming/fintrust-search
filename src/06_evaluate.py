TEST_QUERIES_PATH = PROCESSED_DIR / "queries" / "test_queries.pkl"
TEST_GOLD_PATH    = PROCESSED_DIR / "qrels"   / "test_gold.csv"
ALL_FEATURES_PATH = PROCESSED_DIR / "all_features.pkl"

BASE_DIR          = Path(__file__).resolve().parent.parent
MODELS_DIR        = BASE_DIR / "models"
MODEL_PATH        = MODELS_DIR / "ltr_model.pkl"
SCALER_PATH       = MODELS_DIR / "ltr_scaler.pkl"
INDEX_DIR         = BASE_DIR / "index"

RESULTS_DIR            = BASE_DIR / "results"
EXPERIMENT_RESULTS     = RESULTS_DIR / "experiment_results.csv"
ABLATION_RESULTS       = RESULTS_DIR / "ablation_results.csv"

# Feature column groups for ablation
SOCIAL_COLS  = ["F_SOC_SCORE",  "F_SOC_UPVOTE", "F_SOC_ENGAGE"]
GRAPH_COLS   = ["F_GRAPH_DEG",  "F_GRAPH_BET",  "F_GRAPH_COMM"]
CONTENT_COLS = ["F_CONT_SENT",  "F_CONT_NER",   "F_CONT_MONEY"]
ALL_FEAT_COLS = SOCIAL_COLS + GRAPH_COLS + CONTENT_COLS

